function buildShift() {
  let src = readFileSync(SHIFT_SRC, "utf8");
  // Drop the Node entry-point guard (browser never runs main()).
  src = src.replace(/^if \(require\.main === module\) main\(\);\r?$/m, "");
  // CJS exports -> ESM named exports (same identifiers).
  const m = src.match(/module\.exports = \{([\s\S]*?)\};/);
  if (!m) throw new Error("module.exports block not found in identity-shift.js");
  const names = m[1]
    .split(",")
    .map((s) => s.trim())
    .filter(Boolean)
    .map((s) => s.split(":")[0].trim());
  src = src.replace(/module\.exports = \{[\s\S]*?\};/, `export { ${names.join(", ")} };`);
  const header = `/* GENERATED by docs/gallery/build-vendor.mjs from identity-shift.js — DO NOT EDIT BY HAND.\n * Browser-safe ESM copy of the real day/night identity-shift resolver. */\n`;
  return header + src;
}

function buildValidator() {
  let src = readFileSync(VALIDATOR_SRC, "utf8");
  if (!src.includes('import { createHash } from "node:crypto";')) {
    throw new Error("expected node:crypto import not found in validator.js");
  }
  src = src.replace('import { createHash } from "node:crypto";', SHA256_SHIM.trim());
  const header = `/* GENERATED by docs/gallery/build-vendor.mjs from genome/validator.js — DO NOT EDIT BY HAND.\n * Browser-safe ESM copy of the real genome validator (node:crypto replaced by a\n * pure-JS SHA-256 shim exposing the identical createHash surface). */\n`;
  return header + src;
}

mkdirSync(OUT, { recursive: true });
writeFileSync(join(OUT, "identity-shift.esm.js"), buildShift());
writeFileSync(join(OUT, "validator.esm.js"), buildValidator());
console.log("vendor written to", OUT);
