/*
 * build-vendor.mjs — generate browser-safe ESM vendor copies of the REAL
 * identity-shift.js resolver and genome/validator.js for the Genome Gallery.
 *
 * The gallery runs the actual modules in the browser (no re-implementations).
 * - identity-shift.js is CommonJS: strip the entry-point guard, turn
 *   module.exports into ESM named exports.
 * - genome/validator.js is already ESM but imports node:crypto: replace that
 *   import with a pure-JS SHA-256 shim exposing the same createHash surface.
 *
 * The gallery test suite regenerates into a temp dir and byte-compares
 * against the committed vendor files, so hand edits are caught.
 *
 * Usage: node docs/gallery/build-vendor.mjs [outdir]
 * Default outdir: docs/gallery/vendor
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..", "..");
const OUT = process.argv[2] || join(HERE, "vendor");

const SHIFT_SRC = join(ROOT, "identity-shift.js");
const VALIDATOR_SRC = join(ROOT, "genome", "validator.js");

